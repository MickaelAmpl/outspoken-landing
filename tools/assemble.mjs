#!/usr/bin/env node
// Builds the public site into ./dist (cleaned first): inlines src/parts/<name>.html into the src pages, replaces {{KEY}} from site.config.json,
// handles <!-- @if KEY --> ... <!-- @endif --> blocks, copies public static files. Needs Node 22, no dependencies.
import { readFileSync, writeFileSync, existsSync, mkdirSync, rmSync, cpSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const fail = (msg) => { console.error('assemble: ' + msg); process.exit(1); };

const config = JSON.parse(readFileSync(join(root, 'site.config.json'), 'utf8'));
const privacy = config.PUBLISH_PRIVACY === true;

// page: source file in src/. anchorPrefix: in-page "#anchor" links (header, footer, buttons) become anchorPrefix + "#anchor" (null = leave as is).
function build(page, anchorPrefix) {
  let html = readFileSync(join(root, 'src', page), 'utf8');

  html = html.replace(/^[ \t]*<!-- @part ([a-z0-9-]+) -->[ \t]*$/gm, (_, name) => {
    const file = join(root, 'src/parts', name + '.html');
    if (!existsSync(file)) fail(`missing part src/parts/${name}.html`);
    return readFileSync(file, 'utf8').replace(/\s+$/, '');
  });
  const leftover = html.match(/<!-- @part [^>]*-->/);
  if (leftover) fail(`${page}: unresolved part marker: ` + leftover[0]);

  // conditional blocks: kept when config[KEY] === true, removed otherwise (whole lines)
  html = html.replace(/^[ \t]*<!-- @if ([A-Z0-9_]+) -->[ \t]*\n([\s\S]*?)^[ \t]*<!-- @endif -->[ \t]*\n/gm, (_, key, body) => {
    if (!(key in config)) fail(`${page}: unknown @if key ${key}`);
    return config[key] === true ? body : '';
  });
  if (/<!-- @(if|endif)/.test(html)) fail(`${page}: unbalanced @if/@endif`);

  const unknown = new Set();
  html = html.replace(/\{\{([A-Z0-9_]+)\}\}/g, (m, key) => {
    if (!(key in config)) { unknown.add(key); return m; }
    return String(config[key]);
  });
  if (unknown.size) fail(`${page}: unknown {{KEY}} not in site.config.json: ` + [...unknown].join(', '));

  if (anchorPrefix) html = html.replace(/href="#([^"]*)"/g, `href="${anchorPrefix}#$1"`);

  html = bundleCss(page, html);

  writeFileSync(join(dist, page), '<!-- GENERATED by tools/assemble.mjs — edit src/ -->\n' + html);
  console.log('assemble: wrote dist/' + page);
}

// Replaces the page's <link rel="stylesheet" href="..."> tags (read from the built html, in order) with ONE bundle: css/<name>.css.
// Same folder as the sources, so relative url(../fonts/...) in base.css stays valid. Light minify: strip comments, collapse blank lines.
const bundleNames = { 'index.html': 'site', '404.html': '404', 'privacy.html': 'privacy' };
const cssBundles = [];   // { out, text }, written after dist is cleaned
function bundleCss(page, html) {
  const re = /^[ \t]*<link rel="stylesheet" href="([^"]+)">[ \t]*\n/gm;
  const hrefs = [...html.matchAll(re)].map((m) => m[1]);
  if (!hrefs.length) return html;
  const abs = hrefs[0].startsWith('/');
  const text = hrefs.map((h) => {
    const file = join(root, h.replace(/^\//, ''));
    if (!/^(\/)?css\/[a-z0-9\/_-]+\.css$/i.test(h)) fail(`${page}: unexpected stylesheet href ${h}`);
    if (!existsSync(file)) fail(`${page}: missing stylesheet ${h}`);
    return readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/[ \t]+$/gm, '').replace(/\n{2,}/g, '\n').trim();
  }).join('\n');
  const out = `css/${bundleNames[page] || page.replace(/\.html$/, '')}.css`;
  cssBundles.push({ out, text: text + '\n' });
  // Version stamp from the bundle's content: a new deploy with changed CSS gets a new URL, so no browser reuses a stale cached copy.
  const v = createHash('sha256').update(text).digest('hex').slice(0, 10);
  let first = true;
  return html.replace(re, () => { if (!first) return ''; first = false; return `  <link rel="stylesheet" href="${abs ? '/' : ''}${out}?v=${v}">\n`; });
}

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

build('index.html', null);
build('404.html', '/');                                  // served for any missing URL at any depth: absolute asset paths and "/#section" links
if (privacy) build('privacy.html', 'index.html');

// public static files only
const keepLegalCss = (src) => privacy || !src.endsWith('legal.css');
for (const dir of ['css', 'js', 'fonts', 'img']) {
  if (!existsSync(join(root, dir))) fail(`missing folder ${dir}/`);
  cpSync(join(root, dir), join(dist, dir), { recursive: true, filter: keepLegalCss });
}
// bundles replace the individual stylesheets: css/tokens.css, base.css and css/sections/ are not shipped
rmSync(join(dist, 'css/sections'), { recursive: true, force: true });
rmSync(join(dist, 'css/tokens.css'), { force: true });
rmSync(join(dist, 'css/base.css'), { force: true });
for (const { out, text } of cssBundles) { writeFileSync(join(dist, out), text); console.log(`assemble: wrote dist/${out} (${text.length} bytes)`); }
for (const f of ['favicon.ico', 'apple-touch-icon.png', 'robots.txt', 'sitemap.xml', '_headers']) {
  if (!existsSync(join(root, f))) fail(`missing file ${f}`);
  cpSync(join(root, f), join(dist, f));
}
console.log(`assemble: done (PUBLISH_PRIVACY=${privacy})`);
